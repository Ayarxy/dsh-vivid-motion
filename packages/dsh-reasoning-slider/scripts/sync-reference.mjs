import fs from 'node:fs';
import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { adaptHostSelection, createCenteredPosition, hostCSS } from './host-adapter.mjs';

// The frozen HTML is the source of truth. Do not hand-edit generated client.js.
const referenceURL = new URL('../../../tests/reasoning-visual.html', import.meta.url);
const clientURL = new URL('../lib/client.js', import.meta.url);
const html = fs.readFileSync(referenceURL, 'utf8');
assert.equal(createHash('sha256').update(html).digest('hex'),
  'bc6d51e80ab18dd1f41229d9007e118eb55ca6357d3c2bedb136f20eb0591e28', 'Frozen reference changed');
const component = html.match(/<script data-reference-source="\.\.\/packages\/dsh-reasoning-slider\/lib\/client\.js">\r?\n([\s\S]*?)<\/script>/)?.[1];
const demo = html.match(/<script data-reference-source="reasoning-visual\.js">\r?\n([\s\S]*?)<\/script>/)?.[1];
const pageCSS = html.match(/<style>\r?\n([\s\S]*?)<\/style>/)?.[1];
assert.ok(component && demo && pageCSS, 'Missing reference source block');
const primitives = demo.slice(demo.indexOf('  const icons='), demo.indexOf('  const plugin='));
assert.ok(primitives.includes('useAnchoredPosition') && primitives.includes('for(const [name,path]'));
const hostComponent = adaptHostSelection(component);
const maximumColor = component.match(/--rs-purple:([^;]+);/)?.[1];
assert.ok(maximumColor, 'Missing reference maximum-effort color');

// Inherit the page's exact component palette and typography without applying
// its demo header, body background or 640px stage layout to the entire DSH app.
const scope = ':where(.dsh-reasoning-root, .dsh-reasoning-panel)';
const rules = [...pageCSS.matchAll(/([^{}]+)\{([^{}]*)\}/g)];
const declarations = selector => {
  const rule = rules.find(match => match[1].trim() === selector);
  assert.ok(rule, `Missing page rule: ${selector}`);
  return rule[2];
};
const inheritedBody = declarations('body').split(';').filter(part => /^\s*(font|color):/.test(part)).join(';') + '; ';
const darkTokens = declarations('body.dark').split(';').filter(part => /^\s*--/.test(part)).join(';') + '; ';
const scopedPageCSS = [
  `${scope} {${declarations(':root')} --rs-purple:${maximumColor}; }`,
  `${scope} {${inheritedBody}}`,
  `:where(.dsh-reasoning-root button, .dsh-reasoning-panel button) {${declarations('button')}}`,
  ...rules.filter(match => match[1].trim().startsWith('.dsh-reasoning-')).map(match => match[0].trim()),
  `body.dark ${scope} {${darkTokens}}`
].join('\n');

const generated = `// Generated by scripts/sync-reference.mjs from the frozen reasoning-visual.html.
// Slider, CSS, shaders, motion and presentation dependencies are copied verbatim.
// Explicit host adapters position/animate the popup, isolate CSS and queue selections.
(() => {
  const browser = window;
  let referenceModule;
  function captureReference(window) {
// BEGIN REFERENCE COMPONENT WITH HOST SELECTION ADAPTER
${hostComponent}// END REFERENCE COMPONENT WITH HOST SELECTION ADAPTER
    // Factories close over this binding; restore the real Window before loading.
    window = browser;
  }
  captureReference({ __ModuleLoader__: { load(module) { referenceModule = module; } } });
  browser.__ModuleLoader__.load({
    id: referenceModule.id,
    factory(require) {
      const React = require("react"), h = React.createElement;
// BEGIN VERBATIM PRESENTATION DEPENDENCIES
${primitives}// END VERBATIM PRESENTATION DEPENDENCIES
      const hostPrimitives = { ...primitives, useAnchoredPosition: (${createCenteredPosition.toString()})(React) };
      const plugin = referenceModule.factory(name => name === "@deepseek-ai/dsh-client-ui-primitives" ? hostPrimitives : require(name));
      const pageCSS = ${JSON.stringify(scopedPageCSS)};
      const hostCSS = ${JSON.stringify(hostCSS)};
      return {
        ...plugin,
        apply(ctx) {
          ctx.effect(() => {
            const style = document.createElement("style");
            style.dataset.plugin = "dsh-reasoning-slider-page";
            style.textContent = pageCSS;
            document.head.append(style);
            return () => style.remove();
          }, "dsh-reasoning-slider: reference page inheritance");
          const result = plugin.apply(ctx);
          ctx.effect(() => {
            const style = document.createElement("style");
            style.dataset.plugin = "dsh-reasoning-slider-host";
            style.textContent = hostCSS;
            document.head.append(style);
            return () => style.remove();
          }, "dsh-reasoning-slider: host CSS isolation");
          return result;
        }
      };
    }
  });
})();
`;

if (process.argv.includes('--check')) {
  assert.equal(fs.readFileSync(clientURL, 'utf8'), generated, 'client.js differs from the reference plus explicit host adapters');
} else {
  fs.writeFileSync(clientURL, generated);
}
console.log(`${process.argv.includes('--check') ? 'Verified' : 'Generated'}: reference slider, CSS, motion and ${Buffer.byteLength(primitives)} original presentation dependency bytes preserved; explicit popup motion, position, selection and CSS adapters.`);
